async function main() {
  const product = await prisma.product.findUnique({ where: { slug: "amish-secrets" } });
  if (!product) throw new Error("Product amish-secrets not found");

  const locales = Object.keys(translations);
  let total = 0;

  for (const locale of locales) {
    const sections = translations[locale];
    for (const [section, content] of Object.entries(sections)) {
      await prisma.productTranslation.upsert({
        where: { productId_locale_section: { productId: product.id, locale, section } },
        update: { content },
        create: { productId: product.id, locale, section, content },
      });
      total++;
    }
  }

  console.log(`✅ Saved ${total} translations (${locales.length} locales × 7 sections each)`);
  await prisma.$disconnect();
}

